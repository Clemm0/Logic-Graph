// Bundles every package in packages/* into dist/<plugin-id>/ (main.js, manifest.json, styles.css).
//   npm run build                 one-off build
//   npm run dev                   rebuild on every change
//   VAULT=/path/to/vault npm run dev   ...and copy into <vault>/.obsidian/plugins/<id>/ after each build
import esbuild from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const watch = process.argv.includes('--watch');
const only = process.argv.find(a => a.startsWith('--only='))?.slice(7);
const vault = process.env.VAULT;

const packages = fs.readdirSync(path.join(root, 'packages'))
  .map(name => ({ dir: path.join(root, 'packages', name), pkg: JSON.parse(fs.readFileSync(path.join(root, 'packages', name, 'package.json'), 'utf8')) }))
  .filter(p => p.pkg.obsidian && (!only || p.pkg.obsidian.id === only));

function copyStatic({ dir, pkg }) {
  const id = pkg.obsidian.id, out = path.join(root, 'dist', id);
  fs.mkdirSync(out, { recursive: true });
  fs.copyFileSync(path.join(dir, 'manifest.json'), path.join(out, 'manifest.json'));
  const stylesDir = pkg.obsidian.styles && path.join(dir, pkg.obsidian.styles);
  if (stylesDir && fs.existsSync(stylesDir)) {
    const css = fs.readdirSync(stylesDir).filter(f => f.endsWith('.css')).sort()
      .map(f => fs.readFileSync(path.join(stylesDir, f), 'utf8')).join('\n');
    fs.writeFileSync(path.join(out, 'styles.css'), css);
  }
  if (vault) {
    const target = path.join(vault, '.obsidian', 'plugins', id);
    fs.mkdirSync(target, { recursive: true });
    for (const f of fs.readdirSync(out)) fs.copyFileSync(path.join(out, f), path.join(target, f));
    console.log(`  copied to ${target}`);
  }
}

for (const p of packages) {
  const id = p.pkg.obsidian.id;
  const options = {
    entryPoints: [path.join(p.dir, p.pkg.obsidian.entry)],
    outfile: path.join(root, 'dist', id, 'main.js'),
    bundle: true,
    format: 'cjs',
    platform: 'browser',
    target: 'es2020',
    external: ['obsidian', 'electron'],
    sourcemap: watch ? 'inline' : false,
    minify: false,                                  // keep the shipped file readable (plugin review, bug reports)
    banner: { js: `/* ${id} ${JSON.parse(fs.readFileSync(path.join(p.dir, 'manifest.json'), 'utf8')).version} - generated by esbuild from packages/${path.basename(p.dir)}/src. Do not edit: edit src/ and run "npm run build". */` },
    logLevel: 'info',
    plugins: [{ name: 'copy-static', setup(b) { b.onEnd(() => copyStatic(p)); } }],
  };
  if (watch) { const ctx = await esbuild.context(options); await ctx.watch(); console.log(`watching ${id}…`); }
  else { await esbuild.build(options); }
}
